#!/usr/bin/env python3
"""Re-run the 62 test-run judge JSONs (7-geo-all-types/test-run/judge/, read-only) through the v2.2 engine.
No schema adaptation is needed: v2.2 only adds optional fields (downgrade_reason, evidence_type); the v2.1 judge
files have neither, so every proposed_level is ignored (no downgrade_reason) and every pass is a quote.
Columns: v2.1 = original v2.1 engine; compat = v2.2 engine with rules=v2.1 (must equal v2.1);
level-only = v2.2 level rule with the v2.2 check rules switched off; v2.2 = full v2.2 rules.
Writes testrun_rerun_v2.2.md and testrun_rerun_v2.2.csv."""
import csv, copy, glob, importlib.util, json, os, statistics as st
from common import W, calc, PROJ, TESTRUN, ROOT

spec = importlib.util.spec_from_file_location("calc21", os.path.join(PROJ, "4-scoring-project-v2.1", "GEO Elec Project", "skill", "geo-research", "scripts", "geo_score_calc.py"))
c21 = importlib.util.module_from_spec(spec); spec.loader.exec_module(c21)
W21 = c21.load(os.path.join(PROJ, "4-scoring-project-v2.1", "GEO Elec Project", "skill", "geo-research", "assets", "weights.json"))
W_level_only = copy.deepcopy(W)
for k in ("note_allowed_checks", "block_dependent_checks", "na_is_fail", "level_anchor_overrides"):
    W_level_only.pop(k, None)
same_w = all(W21[k] == W[k] for k in ("page_types", "families", "stage_multipliers", "gates", "penalties", "penalty_cap", "bands", "level_anchors", "level_caps"))

rows = []
for f in sorted(glob.glob(os.path.join(TESTRUN, "judge", "*.json"))):
    pid = os.path.basename(f)[:-5]
    j = json.load(open(f, encoding="utf-8"))
    a = c21.compute(j, W21, True)
    b = calc.compute(j, W, True, rules="v2.1")
    d = calc.compute(j, W_level_only, True, rules="v2.2")
    c = calc.compute(j, W, True, rules="v2.2")
    lv = lambda r: {x["id"]: x["level"] for x in r["criteria"]}
    la, ld, lc = lv(a), lv(d), lv(c)
    up = sum(1 for k in la if k in ld and ld[k] > la[k]); dn = sum(1 for k in la if k in ld and ld[k] < la[k])
    pa, pd = {x["id"]: x["points"] for x in a["criteria"]}, {x["id"]: x["points"] for x in d["criteria"]}
    to5 = sum(pd[k] - pa[k] for k in la if k in ld and ld[k] > la[k] and ld[k] == 5)
    below5 = sum(pd[k] - pa[k] for k in la if k in ld and ld[k] > la[k] and ld[k] < 5)
    chk = [k for k in set(ld) | set(lc) if ld.get(k) != lc.get(k)]
    rows.append(dict(id=pid, key=a["page_type_key"], stage=a["stage"], v21=a["final_score"], compat=b["final_score"],
                     level_only=d["final_score"], v22=c["final_score"], d_level=d["final_score"] - a["final_score"],
                     d_checks=c["final_score"] - d["final_score"], d_total=c["final_score"] - a["final_score"],
                     band21=a["band"], band22=c["band"], crit_up=up, crit_down=dn, check_rule_criteria=";".join(sorted(chk)), pts_to5=round(to5, 2), pts_below5=round(below5, 2)))

with open(os.path.join(ROOT, "testrun_rerun_v2.2.csv"), "w", newline="", encoding="utf-8") as fh:
    w = csv.DictWriter(fh, fieldnames=list(rows[0])); w.writeheader(); w.writerows(rows)

def summ(xs):
    return f"mean {st.mean(xs):+.1f}, median {st.median(xs):+g}, mean |d| {st.mean(abs(x) for x in xs):.1f}, range {min(xs):+d}..{max(xs):+d}"

L = ["# Test-run re-run through the v2.2 engine (generated by rerun_testrun.py)\n",
     f"Input: {len(rows)} judge JSONs from `7-geo-all-types/test-run/judge/` (unchanged). Weights {W['version']}; weights identical to v2.1 apart from the new rule blocks: **{same_w}**.\n",
     f"compat (v2.2 engine, rules=v2.1) reproduces the v2.1 engine on {sum(r['compat'] == r['v21'] for r in rows)}/{len(rows)} files.\n",
     "## Deltas\n",
     f"- **Level rule alone** (level = ceiling; proposed levels ignored because no file has a downgrade_reason): {summ([r['d_level'] for r in rows])}. Pages moved: {sum(r['d_level'] != 0 for r in rows)}/{len(rows)}. Criterion levels raised {sum(r['crit_up'] for r in rows)}, lowered {sum(r['crit_down'] for r in rows)}.",
     f"  - Split: criteria raised to 5 (all checks pass; v2.1 judges proposed 4) add {st.mean(r['pts_to5'] for r in rows):.1f} raw pts/page; criteria raised to a ceiling below 5 (judge proposed under the ceiling) add {st.mean(r['pts_below5'] for r in rows):.1f} raw pts/page.",
     f"- **v2.2 check rules on top** (na -> fail for missing blocks / U1 c4, case_study U9 anchor override): {summ([r['d_checks'] for r in rows])}. Pages moved: {sum(r['d_checks'] != 0 for r in rows)}.",
     f"- **Total engine effect**: {summ([r['d_total'] for r in rows])}. Band changes: {sum(r['band21'] != r['band22'] for r in rows)} ({', '.join(r['id'] + ' ' + r['band21'] + '->' + r['band22'] for r in rows if r['band21'] != r['band22']) or 'none'}).\n",
     "By type (mean level-rule delta / mean total delta):\n", "| key | n | level rule | total |", "|---|---|---|---|"]
by = {}
for r in rows:
    by.setdefault(r["key"], []).append(r)
for k, rs in by.items():
    L.append(f"| {k} | {len(rs)} | {st.mean(r['d_level'] for r in rs):+.1f} | {st.mean(r['d_total'] for r in rs):+.1f} |")
L += ["", "## Per page", "", "| id | key | stage | v2.1 | compat | level rule only | v2.2 | d level | d checks | d total | bands | criteria changed by check rules |", "|---|---|---|---|---|---|---|---|---|---|---|---|"]
for r in rows:
    L.append(f"| {r['id']} | {r['key']} | {r['stage']} | {r['v21']} | {r['compat']} | {r['level_only']} | {r['v22']} | {r['d_level']:+d} | {r['d_checks']:+d} | {r['d_total']:+d} | {r['band21']} -> {r['band22']} | {r['check_rule_criteria'] or '-'} |")
L.append("\nNote: these are engine effects only, on fixed v2.1 judgements. Judging effects of the new prompts (stage test, G1 materiality, hidden content counted once, notes) need a fresh judge run.")
open(os.path.join(ROOT, "testrun_rerun_v2.2.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
print("\n".join(L[:14]))
